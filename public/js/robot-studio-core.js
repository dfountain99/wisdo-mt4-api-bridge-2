export const ROBOT_STUDIO_VERSION = 1;
export const DRAFT_KEY = 'wisdo.robot-studio.draft.v1';

export function createDraft() {
  return {
    version: ROBOT_STUDIO_VERSION,
    name: 'My First WISDO Robot',
    magic: 930001,
    direction: 'both',
    fastEma: 9,
    slowEma: 21,
    rsiEnabled: false,
    rsiPeriod: 14,
    buyRsiMin: 50,
    sellRsiMax: 50,
    sessionEnabled: false,
    sessionStart: 8,
    sessionEnd: 18,
    moneyMode: 'risk',
    riskPercent: 1,
    fixedLots: 0.01,
    stopPips: 25,
    takePips: 50,
    maxSpreadPips: 2,
    slippagePoints: 30
  };
}

function numberOr(value, fallback) {
  if (value === '' || value === null || value === undefined) return fallback;
  const num = Number(value);
  return Number.isFinite(num) ? num : fallback;
}

export function normalizeDraft(source = {}) {
  if (!source || typeof source !== 'object' || Array.isArray(source)) {
    throw new Error('Invalid strategy file.');
  }
  const base = createDraft();
  const normalized = { ...base };
  normalized.name = String(source.name ?? base.name).replace(/[^A-Za-z0-9 _-]/g, '').slice(0, 48).trim();
  for (const key of ['magic', 'fastEma', 'slowEma', 'rsiPeriod', 'buyRsiMin', 'sellRsiMax', 'sessionStart', 'sessionEnd', 'slippagePoints']) {
    normalized[key] = numberOr(source[key], base[key]);
  }
  for (const key of ['riskPercent', 'fixedLots', 'stopPips', 'takePips', 'maxSpreadPips']) {
    normalized[key] = numberOr(source[key], base[key]);
  }
  normalized.direction = String(source.direction ?? base.direction);
  normalized.moneyMode = String(source.moneyMode ?? base.moneyMode);
  normalized.rsiEnabled = source.rsiEnabled === true;
  normalized.sessionEnabled = source.sessionEnabled === true;
  return normalized;
}

export function validateDraft(raw) {
  const d = normalizeDraft(raw);
  const errors = [];
  const integer = (key, min, max) => {
    if (!Number.isInteger(d[key]) || d[key] < min || d[key] > max) errors.push(key + ' must be a whole number between ' + min + ' and ' + max + '.');
  };
  const range = (key, min, max) => {
    if (!(d[key] >= min && d[key] <= max)) errors.push(key + ' must be between ' + min + ' and ' + max + '.');
  };
  if (!d.name) errors.push('Give the robot a name.');
  if (!['buy', 'sell', 'both'].includes(d.direction)) errors.push('Select a supported trade direction.');
  if (!['fixed', 'risk'].includes(d.moneyMode)) errors.push('Select a position sizing mode.');
  integer('magic', 100000, 1999999999);
  integer('fastEma', 2, 100);
  integer('slowEma', 3, 300);
  if (d.fastEma >= d.slowEma) errors.push('Fast EMA must be smaller than slow EMA.');
  integer('rsiPeriod', 2, 100);
  integer('buyRsiMin', 1, 99);
  integer('sellRsiMax', 1, 99);
  integer('sessionStart', 0, 23);
  integer('sessionEnd', 0, 23);
  if (d.sessionEnabled && d.sessionStart === d.sessionEnd) errors.push('Session start and end must be different.');
  integer('slippagePoints', 0, 200);
  range('fixedLots', 0.01, 5);
  range('riskPercent', 0.1, 5);
  range('stopPips', 1, 1000);
  range('takePips', 1, 2000);
  range('maxSpreadPips', 0.1, 100);
  return errors;
}

export function describeFlow(raw) {
  const d = normalizeDraft(raw);
  const steps = [
    { title: 'New completed candle', detail: 'Evaluate once on the next chart candle.' },
    { title: 'EMA crossover', detail: 'Fast EMA ' + d.fastEma + ' crosses slow EMA ' + d.slowEma + '.' }
  ];
  if (d.rsiEnabled) steps.push({ title: 'RSI confirmation', detail: 'Buy RSI > ' + d.buyRsiMin + '; sell RSI < ' + d.sellRsiMax + '.' });
  if (d.sessionEnabled) steps.push({ title: 'Trading schedule', detail: d.sessionStart + ':00–' + d.sessionEnd + ':00 broker server time (overnight supported).' });
  steps.push({ title: 'Safety checks', detail: 'Skip if an order is open, spread exceeds ' + d.maxSpreadPips + ' pips, or volume/stops are invalid.' });
  steps.push({ title: 'Trade entry', detail: d.direction + ' · ' + (d.moneyMode === 'risk' ? d.riskPercent + '% equity-risk target' : d.fixedLots + ' lots') });
  steps.push({ title: 'Predefined exit', detail: d.stopPips + ' pip stop · ' + d.takePips + ' pip target.' });
  return steps;
}

export function generateMql4(raw) {
  const d = normalizeDraft(raw);
  const errors = validateDraft(d);
  if (errors.length) throw new Error(errors.join('\n'));
  const b = (value) => value ? 'true' : 'false';
  const lines = [
    '// Generated by WISDO Robot Studio v1 — experimental MT4 starter EA.',
    '// Inspect, compile in MetaEditor, backtest, and run on DEMO before using live.',
    '// Not a guarantee of trading performance. Uses chart timeframe and broker server time.',
    '#property strict',
    '#property version "1.00"',
    '',
    'input string RobotName = ' + JSON.stringify(d.name) + ';',
    'input int MagicNumber = ' + d.magic + ';',
    'input int FastEMA = ' + d.fastEma + ';',
    'input int SlowEMA = ' + d.slowEma + ';',
    'input bool AllowBuy = ' + b(d.direction !== 'sell') + ';',
    'input bool AllowSell = ' + b(d.direction !== 'buy') + ';',
    'input bool UseRSI = ' + b(d.rsiEnabled) + ';',
    'input int RSIPeriod = ' + d.rsiPeriod + ';',
    'input int BuyRSIMin = ' + d.buyRsiMin + ';',
    'input int SellRSIMax = ' + d.sellRsiMax + ';',
    'input bool UseSession = ' + b(d.sessionEnabled) + ';',
    'input int SessionStartHour = ' + d.sessionStart + ';',
    'input int SessionEndHour = ' + d.sessionEnd + ';',
    'input bool UseRiskPercent = ' + b(d.moneyMode === 'risk') + ';',
    'input double RiskPercent = ' + d.riskPercent + ';',
    'input double FixedLots = ' + d.fixedLots + ';',
    'input double StopPips = ' + d.stopPips + ';',
    'input double TargetPips = ' + d.takePips + ';',
    'input double MaxSpreadPips = ' + d.maxSpreadPips + ';',
    'input int SlippagePoints = ' + d.slippagePoints + ';',
    '',
    'datetime g_lastCandle = 0;',
    'double PipSize() { return (Digits == 3 || Digits == 5) ? 10.0 * Point : Point; }',
    '',
    'bool HasOwnOpenOrder() {',
    '  for (int i = OrdersTotal() - 1; i >= 0; i--) {',
    '    if (!OrderSelect(i, SELECT_BY_POS, MODE_TRADES)) continue;',
    '    if (OrderSymbol() != Symbol() || OrderMagicNumber() != MagicNumber) continue;',
    '    if (OrderType() == OP_BUY || OrderType() == OP_SELL) return true;',
    '  }',
    '  return false;',
    '}',
    '',
    'bool SessionAllowsTrade() {',
    '  if (!UseSession) return true;',
    '  int hour = TimeHour(TimeCurrent());',
    '  if (SessionStartHour < SessionEndHour)',
    '    return hour >= SessionStartHour && hour < SessionEndHour;',
    '  return hour >= SessionStartHour || hour < SessionEndHour;',
    '}',
    '',
    'double LotsForStop(double stopInPips) {',
    '  double minLot = MarketInfo(Symbol(), MODE_MINLOT);',
    '  double maxLot = MarketInfo(Symbol(), MODE_MAXLOT);',
    '  double step = MarketInfo(Symbol(), MODE_LOTSTEP);',
    '  if (step <= 0 || minLot <= 0 || maxLot < minLot) return 0;',
    '  double lots = FixedLots;',
    '  if (UseRiskPercent) {',
    '    double tickValue = MarketInfo(Symbol(), MODE_TICKVALUE);',
    '    double tickSizePoints = MarketInfo(Symbol(), MODE_TICKSIZE);',
    '    if (tickValue <= 0 || tickSizePoints <= 0) return 0;',
    '    double valuePerPipPerLot = tickValue * PipSize() / (tickSizePoints * Point);',
    '    if (valuePerPipPerLot <= 0) return 0;',
    '    lots = (AccountEquity() * RiskPercent / 100.0) / (stopInPips * valuePerPipPerLot);',
    '  }',
    '  // Round DOWN to broker lot step; do not increase intended risk to reach minimum.',
    '  lots = MathFloor((lots + 1e-9) / step) * step;',
    '  if (lots < minLot) return 0;',
    '  return NormalizeDouble(MathMin(lots, maxLot), 3);',
    '}',
    '',
    'void SubmitTrade(int side) {',
    '  RefreshRates();',
    '  double pip = PipSize();',
    '  if ((Ask - Bid) / pip > MaxSpreadPips) return;',
    '  double brokerMinDistance = MarketInfo(Symbol(), MODE_STOPLEVEL) * Point;',
    '  if (StopPips * pip <= brokerMinDistance || TargetPips * pip <= brokerMinDistance) {',
    '    Print("WISDO: configured stops are below this broker minimum.");',
    '    return;',
    '  }',
    '  double lots = LotsForStop(StopPips);',
    '  if (lots <= 0 || AccountFreeMarginCheck(Symbol(), side, lots) <= 0) {',
    '    Print("WISDO: order skipped — volume/risk/margin gate.");',
    '    return;',
    '  }',
    '  double price = side == OP_BUY ? Ask : Bid;',
    '  double stop = side == OP_BUY ? price - StopPips * pip : price + StopPips * pip;',
    '  double target = side == OP_BUY ? price + TargetPips * pip : price - TargetPips * pip;',
    '  ResetLastError();',
    '  int ticket = OrderSend(Symbol(), side, lots, NormalizeDouble(price, Digits), SlippagePoints,',
    '                         NormalizeDouble(stop, Digits), NormalizeDouble(target, Digits),',
    '                         RobotName, MagicNumber, 0, clrNONE);',
    '  if (ticket < 0) Print("WISDO: OrderSend failed, MT4 error ", GetLastError());',
    '}',
    '',
    'void OnTick() {',
    '  if (Bars < SlowEMA + 5) return;',
    '  datetime currentCandle = iTime(Symbol(), PERIOD_CURRENT, 0);',
    '  if (currentCandle <= 0 || currentCandle == g_lastCandle) return;',
    '  g_lastCandle = currentCandle;',
    '  if (!IsTradeAllowed() || !SessionAllowsTrade() || HasOwnOpenOrder()) return;',
    '  double fast1 = iMA(Symbol(), 0, FastEMA, 0, MODE_EMA, PRICE_CLOSE, 1);',
    '  double fast2 = iMA(Symbol(), 0, FastEMA, 0, MODE_EMA, PRICE_CLOSE, 2);',
    '  double slow1 = iMA(Symbol(), 0, SlowEMA, 0, MODE_EMA, PRICE_CLOSE, 1);',
    '  double slow2 = iMA(Symbol(), 0, SlowEMA, 0, MODE_EMA, PRICE_CLOSE, 2);',
    '  bool buySignal = fast1 > slow1 && fast2 <= slow2;',
    '  bool sellSignal = fast1 < slow1 && fast2 >= slow2;',
    '  if (UseRSI) {',
    '    double rsi = iRSI(Symbol(), 0, RSIPeriod, PRICE_CLOSE, 1);',
    '    buySignal = buySignal && rsi > BuyRSIMin;',
    '    sellSignal = sellSignal && rsi < SellRSIMax;',
    '  }',
    '  if (AllowBuy && buySignal) SubmitTrade(OP_BUY);',
    '  else if (AllowSell && sellSignal) SubmitTrade(OP_SELL);',
    '}',
    ''
  ];
  return lines.join('\n');
}

export function exportDraftJson(raw) {
  const d = normalizeDraft(raw);
  const errors = validateDraft(d);
  if (errors.length) throw new Error(errors.join('\n'));
  return JSON.stringify({ generator: 'wisdo-robot-studio', ...d }, null, 2) + '\n';
}
